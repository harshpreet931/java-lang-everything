export function JniBuild() {
  const s = useStepper(STEPS.length, { interval: 3000 });
  const st = STEPS[s.i];

  return (
    <div {...s.keys} className="@container outline-none">
      <ol className="flex flex-wrap items-center gap-x-1 gap-y-1.5 text-12" aria-label="steps">
        {STEPS.map((x, i) => (
          <li key={x.tag} className="flex items-center gap-1">
            <button
              onClick={() => s.go(i)}
              className="rounded-xs px-2 py-1 transition-[box-shadow,color] duration-200 ease-jle"
              style={{
                boxShadow: `inset 0 0 0 1px ${i === s.i ? "var(--hot)" : "var(--line-2)"}`,
                color: i === s.i ? "var(--hot)" : i < s.i ? "var(--ink)" : "var(--mute)",
              }}
            >
              {x.tag}
            </button>
            {i < STEPS.length - 1 && <span className="text-faint">→</span>}
          </li>
        ))}
      </ol>
      <div className="mt-4">
        <div className="mb-1 text-11 text-faint">{st.file}</div>
        <pre className="min-h-[16em] overflow-x-auto rounded-md bg-well px-3 py-2.5 text-11 leading-[1.6] whitespace-pre text-ink shadow-[inset_0_0_0_1px_var(--line)] @[560px]:text-12">
          {st.body.split("\n").map((line, i) => (
            <span
              key={i}
              className="block"
              style={{
                color: line.startsWith("WARNING") || line.startsWith("Exception") || line.startsWith("Caused") ? "var(--dead)" : line.startsWith("#") ? "var(--faint)" : undefined,
              }}
            >
              {line || " "}
            </span>
          ))}
        </pre>
      </div>
      <p className="mt-3 min-h-[5em] font-serif text-17 leading-[1.6] text-ink" aria-live="polite">
        {st.note}
      </p>
      <StepControls s={s} className="mt-2" />
    </div>
  );
}
